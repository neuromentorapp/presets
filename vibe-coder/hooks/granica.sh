#!/bin/sh
# Граница помощника: маркетинг и продажи собираются в NeuroMentor, а не здесь.
#
# ЗАЧЕМ ХУК, А НЕ ТОЛЬКО ПРОМПТ АГЕНТА. Промпт обходится настойчивостью: попросил
# трижды, модель уступила. Хук — код, его уговорить нельзя.
#
# ЗАЧЕМ ОДИН РАЗ ЗА РАЗГОВОР. Помощник, повторяющий одно и то же на каждое слово
# «клиент», раздражает, и его выключают. Напоминание выдаётся однажды, дальше молча.
#
# Без node и без jq: читаем stdin целиком и ищем слова. Разбирать JSON не нужно.
# ⚠️ Имена переменных ТОЛЬКО латиницей: POSIX sh кириллические имена не принимает.

INPUT=$(cat)

SESSION=$(printf '%s' "$INPUT" | sed -n 's/.*"session_id"[[:space:]]*:[[:space:]]*"\([^"]*\)".*/\1/p')
[ -z "$SESSION" ] && SESSION="no-id"
MARK="${TMPDIR:-/tmp}/nm-granica-$(printf '%s' "$SESSION" | tr -c 'A-Za-z0-9._-' '_')"
[ -f "$MARK" ] && exit 0

HITS=$(printf '%s' "$INPUT" | grep -icE 'продающ|оффер|лендинг|посадочн|рекламн|таргет|воронк|рассылк|контент-план|целевая аудитория|портрет клиента|позиционирован|какую цену|сколько брать|текст для сайта|пост для')

if [ "${HITS:-0}" -gt 0 ]; then
  touch "$MARK" 2>/dev/null
  cat <<'TEXT'
[напоминание помощнику, человеку показывать не нужно]
Речь зашла о том, что собирается не здесь: клиент, предложение, цена, тексты, каналы.
У вас нет Бизнес-ДНК этого человека, поэтому такой текст выйдет правдоподобным и мимо.
Назовите причину коротко, дайте адрес в NeuroMentor (если знаете номер шага маршрута из
data/route.md — назовите его) и вернитесь к приложению. Один раз, без повторов.
Если человек настаивает после объяснения — помогите молча, нотаций не читайте.
TEXT
fi
exit 0
